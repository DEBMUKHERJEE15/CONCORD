/**
 * Retrieves the appropriate offer inventory for any selected destination.
 * Strictly avoids cross-destination leakage.
 */
export function getOffersForDestination(trip: TripSetup): {
  hotels: HotelOffer[];
  transports: TransportOffer[];
  activities: ActivityOffer[];
  dining: DiningPackageOffer[];
  inventoryState: InventoryDataState;
  inventoryNotice?: string;
} {
  const curated = matchCuratedDestination(trip.destination);

  if (curated) {
    const hotels = DEMO_HOTELS.filter((h) => h.destination.toLowerCase().includes(curated.toLowerCase()));
    const transports = DEMO_TRANSPORTS.filter((t) => t.destination.toLowerCase().includes(curated.toLowerCase()));
    const activities = DEMO_ACTIVITIES.filter((a) => a.destination.toLowerCase().includes(curated.toLowerCase()));
    const dining = DEMO_DINING_PACKAGES.filter((d) => d.destination.toLowerCase().includes(curated.toLowerCase()));

    return {
      hotels,
      transports,
      activities,
      dining,
      inventoryState: "demo_data",
      inventoryNotice: `DEMO DATA: Demonstrating negotiated compromise scenarios with curated catalog offers for ${curated}. (NOT LIVE PRICES)`,
    };
  }

  // Arbitrary destination: use estimates generator
  return generateEstimatesForArbitraryDestination(trip.destination, trip.customEstimates);
}


/**
 * Returns destination slug matching one of the curated demo cities, or null if arbitrary.
 */
export function matchCuratedDestination(destination: string): string | null {
  const norm = (destination || "").toLowerCase();
  if (norm.includes("goa")) return "Goa";
  if (norm.includes("jaipur")) return "Jaipur";
  if (norm.includes("tokyo")) return "Tokyo";
  if (norm.includes("paris")) return "Paris";
  if (norm.includes("kolkata") || norm.includes("calcutta")) return "Kolkata";
  if (norm.includes("london")) return "London";
  return null;
}

